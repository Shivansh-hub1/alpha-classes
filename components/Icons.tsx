export function CourseIconBadge({ level, size = 24 }: { level?: string; icon?: string; size?: number }) {
  const l = (level || "").toLowerCase();
  if (l.includes("med") || l.includes("neet")) return <IconMicroscope size={size} />;
  if (l.includes("jee") || l.includes("comp")) return <IconTarget size={size} />;
  if (l.includes("tech") || l.includes("web") || l.includes("code")) return <IconCode size={size} />;
  if (l.includes("skill") || l.includes("career")) return <IconTrending size={size} />;
  if (l.includes("govt") || l.includes("ssc")) return <IconFileText size={size} />;
  return <IconGraduation size={size} />;
}
